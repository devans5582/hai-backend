"""JSON Schemas for LLM outputs.

Strict-mode compatible: every property required, ``additionalProperties: false``,
enums taken from the vocabularies. Two schemas: a criterion finding and a batch
of link proposals.
"""

from __future__ import annotations

import json
from typing import Any

from hai_ontology.meta import Manifest

UUID_PATTERN = "^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$"


def _meta(manifest: Manifest, title: str, description: str) -> dict[str, Any]:
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": f"https://humaital.com/schemas/{title.lower().replace(' ', '-')}-{manifest.methodology_version}.json",
        "title": title,
        "description": description,
        "x-generated": "generated by hai-ontology from the manifest under ontology/. Do not edit.",
        "x-manifest-hash": manifest.hash,
        "x-ontology-version": manifest.ontology_version,
        "x-methodology-version": manifest.methodology_version,
    }


def finding_schema(manifest: Manifest) -> dict[str, Any]:
    criteria = [c.code for c in manifest.criteria]
    schema = _meta(
        manifest,
        "Criterion Finding",
        "An advisory proposal for one criterion. The rules engine decides; the validator checks every citation.",
    )
    schema.update(
        {
            "type": "object",
            "additionalProperties": False,
            "required": [
                "criterion_code",
                "proposed_level",
                "evidence_link_ids",
                "contradicting_link_ids",
                "uncertainty",
                "reasoning_summary",
            ],
            "properties": {
                "criterion_code": {"type": "string", "enum": criteria},
                "proposed_level": {"type": "integer", "minimum": 1, "maximum": 5},
                "evidence_link_ids": {
                    "type": "array",
                    "items": {"type": "string", "pattern": UUID_PATTERN},
                    "description": "Ids of admissible supporting links shown in the evidence pack.",
                },
                "contradicting_link_ids": {
                    "type": "array",
                    "items": {"type": "string", "pattern": UUID_PATTERN},
                    "description": "Ids of admissible contradicting links shown in the evidence pack.",
                },
                "uncertainty": {"type": "number", "minimum": 0, "maximum": 1},
                "reasoning_summary": {"type": "string", "maxLength": 600},
            },
        }
    )
    return schema


def proposal_schema(manifest: Manifest) -> dict[str, Any]:
    criteria = [c.code for c in manifest.criteria]
    polarity = manifest.vocabularies["polarity"].codes
    schema = _meta(
        manifest,
        "Link Proposals",
        "Proposed evidence links. The proposer may only reference span ids it was shown.",
    )
    schema.update(
        {
            "type": "object",
            "additionalProperties": False,
            "required": ["proposals"],
            "properties": {
                "proposals": {
                    "type": "array",
                    "items": {
                        "type": "object",
                        "additionalProperties": False,
                        "required": ["span_id", "criterion_code", "polarity", "relevance"],
                        "properties": {
                            "span_id": {"type": "string", "pattern": UUID_PATTERN},
                            "criterion_code": {"type": "string", "enum": criteria},
                            "polarity": {"type": "string", "enum": polarity},
                            "relevance": {"type": "number", "minimum": 0, "maximum": 1},
                        },
                    },
                }
            },
        }
    )
    return schema


def render(schema: dict[str, Any]) -> str:
    return json.dumps(schema, indent=2, sort_keys=False) + "\n"
